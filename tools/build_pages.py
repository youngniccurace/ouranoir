def sync_public_config() -> None:
    """Keep the public contact email in js/site-config.js (used by the apply/ app) in sync."""
    f = ROOT / "js/site-config.js"
    text = f.read_text(encoding="utf-8")
    text = re.sub(r'contactEmail: "[^"]*"', f'contactEmail: "{CONTACT_EMAIL}"', text)
    f.write_text(text, encoding="utf-8")


def main() -> None:
    sync_public_config()
    for page in PAGES:
        (ROOT / page["file"]).write_text(build_page(page), encoding="utf-8")
