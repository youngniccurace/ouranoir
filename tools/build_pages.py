# --- Images: {{img:NAME}} or {{img:NAME:extra-classes}} or {{img:NAME:extra-classes:eager}} ------------
# NAME refers to tools/stock-photos.txt (alt text + crop). Two WebP widths are generated per photo.
STOCK = {}
for _line in (Path(__file__).resolve().parent / "stock-photos.txt").read_text(encoding="utf-8").splitlines():
    if _line and not _line.startswith("#"):
        _name, _pid, _crop, _alt = _line.split("|")
        STOCK[_name] = (_crop, _alt)
IMG_SIZES = {
    "square": ((400, 400), (800, 800), "(max-width: 991px) 45vw, 280px"),
    "card": ((480, 360), (960, 720), "(max-width: 767px) 100vw, (max-width: 1199px) 50vw, 380px"),
    "wide": ((640, 480), (1200, 900), "(max-width: 991px) 100vw, 560px"),
}
IMG_RE = re.compile(r"\{\{img:([a-z0-9-]+)(?::([^:}]*))?(?::(eager))?\}\}")


def img_tag(m: re.Match) -> str:
    name, classes, eager = m.group(1), (m.group(2) or "").strip(), m.group(3)
    crop, alt = STOCK[name]
    (w1, h1), (w2, h2), sizes = IMG_SIZES[crop]
    loading = 'fetchpriority="high"' if eager else 'loading="lazy" decoding="async"'
    cls = f' class="{classes}"' if classes else ""
    return (f'<img src="img/stock/{name}-{w2}.webp" srcset="img/stock/{name}-{w1}.webp {w1}w, img/stock/{name}-{w2}.webp {w2}w" '
            f'sizes="{sizes}" width="{w2}" height="{h2}" alt="{esc(alt)}"{cls} {loading}>')


# --- Markup transforms applied to every page --------------------------------
ICON_RE = re.compile(r'<(?:i|span) class="(fas|fab|fa) fa-([a-z0-9-]+)([^"]*)"></(?:i|span)>')
SIZE_CLASSES = {"fa-2x", "fa-3x", "fa-4x", "fa-5x", "fa-7x", "fa-fw"}


def icon_svg(m: re.Match) -> str:
    """Icon font -> inline SVG from a tiny sprite (img/icons.svg). Decorative, hidden from screen readers."""
    style = "fab" if m.group(1) == "fab" else "fas"
    extra = [c for c in m.group(3).split() if c]
    classes = " ".join(["icon"] + [c.replace("fa-", "icon-") if c in SIZE_CLASSES else c for c in extra])
    return f'<svg class="{classes}" aria-hidden="true" focusable="false"><use href="img/icons.svg#{style}-{m.group(2)}"></use></svg>'


def transform(body: str) -> str:
    body = body.replace('img/logo.svg#', versioned('img/logo.svg') + '#')
    body = IMG_RE.sub(img_tag, body)
    body = ICON_RE.sub(icon_svg, body)
    # Entrance animations: animate.css/WOW.js replaced by a lightweight reveal-on-scroll (js/main.js).
    # Content above the fold is no longer animated so it paints immediately.
    body = re.sub(r"\s*\banimated (?:bounceInDown|bounceInLeft|bounceInUp|zoomIn|fadeInUp)\b", "", body)
    body = re.sub(r"\bwow (?:bounceInUp|fadeInUp|bounceInDown)\b", "reveal", body)
    body = body.replace("data-wow-delay=", "data-reveal-delay=")
    return body


def make_absolute(page_html: str) -> str:
    """For 404.html: make every local URL root-relative so it works at any missing path."""
    def fix(m: re.Match) -> str:
        attr, url = m.group(1), m.group(2)
        if re.match(r"^(https?:|mailto:|tel:|#|/|data:)", url):
            return m.group(0)
        return f'{attr}="/{url}"'
    return re.sub(r'\b(href|src)="([^"]*)"', fix, page_html)


def fill_tokens(text: str) -> str:
    return (text.replace("{{SITE_URL}}", SITE_URL)
                .replace("{{BUSINESS_NAME}}", esc(BUSINESS_NAME))
                .replace("{{CONTACT_EMAIL}}", CONTACT_EMAIL)
                .replace("{{LAST_UPDATED}}", LAST_UPDATED))


def build_page(page: dict) -> str:
    body = (CONTENT / f"{page['content']}.html").read_text(encoding="utf-8")
    doc = head(page) + navbar(page["nav"]) + "\n" + body + "\n" + footer()
    doc = fill_tokens(transform(doc))
    if page.get("absolute"):
        doc = make_absolute(doc)
    return doc


def write_sitemap() -> None:
    today = dt.date.today().isoformat()
    entries = [(p["path"], p["priority"]) for p in PAGES if p["path"] is not None and not p.get("noindex")] + EXTRA_SITEMAP
    urls = "\n".join(
        f"  <url>\n    <loc>{abs_url(path)}</loc>\n    <lastmod>{today}</lastmod>\n    <priority>{prio}</priority>\n  </url>"
        for path, prio in entries
    )
    (ROOT / "sitemap.xml").write_text(
        f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{urls}\n</urlset>\n',
        encoding="utf-8")


