def versioned(path: str) -> str:
    """Append a content hash so files can be cached long-term and still update instantly."""
    f = ROOT / path
    if not f.exists():
        return path
    return f"{path}?v={hashlib.sha1(f.read_bytes()).hexdigest()[:10]}"


def abs_url(path: str) -> str:
    return f"{SITE_URL}/{path}" if path else f"{SITE_URL}/"


def esc(text: str) -> str:
    return html.escape(text, quote=True)


