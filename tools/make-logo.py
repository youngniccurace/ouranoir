#!/usr/bin/env python3
"""
Builds the OuraNoir logo files from the brand fonts (text is converted to vector paths,
so the logo looks identical everywhere and needs no font to load).

Concept "Aura Ring": a gold halo (the aura - and the O of Oura) around an editorial N,
with an azure glint where the halo catches the light. Together the ring + N read "ON".

    pip install fonttools brotli uharfbuzz
    python3 tools/make-logo.py            # then: cd tools && npm run images && npm run build

Outputs
  img/logo.svg                 sprite used by the site (<use href="img/logo.svg#logo-lockup">);
                               colours come from CSS variables, so it adapts to light/dark mode
  img/favicon.svg              symbol on a Midnight tile
  img/brand/*.svg              standalone files for social media, documents, partners
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
from logo_glyphs import text_path, arc, spark  # noqa: E402

WORDMARK = "editorial"   # "editorial" (Playfair), "script" (Playball) or "caps" (spaced capitals)

FONTS = ROOT / "fonts"
PLAYFAIR = str(FONTS / "playfair-display-latin-700-normal.woff2")
PLAYFAIR_ITALIC = str(FONTS / "playfair-display-latin-700-italic.woff2")
PLAYBALL = str(HERE / "node_modules/@fontsource/playball/files/playball-latin-400-normal.woff2")  # only for WORDMARK = "script"

# Brand colours (see brand.html)
GOLD, DEEP_GOLD, AZURE, AZURE_GLOW = "#D4A762", "#8F6526", "#1E9BD7", "#5BBEEB"
NOIR, IVORY, MIDNIGHT = "#050709", "#F4F1EC", "#0A0F17"
LIGHT = {"ring": GOLD, "ink": NOIR, "oura": DEEP_GOLD, "spark": AZURE}
DARK = {"ring": GOLD, "ink": IVORY, "oura": GOLD, "spark": AZURE_GLOW}


def centered(font, text, size, cx, baseline):
    _, _, b = text_path(font, text, size, 0, 0)
    return text_path(font, text, size, cx - (b[0] + b[2]) / 2, baseline)[0]


def mark(c):
    """Aura Ring symbol in a 100x100 box."""
    ring = arc(50, 50, 38, 62, 28 + 360)          # open where the glint sits
    n = centered(PLAYFAIR, "N", 50, 50, 68)
    return (f'<path d="{ring}" fill="none" stroke="{c["ring"]}" stroke-width="6.5" stroke-linecap="round"/>'
            f'<path d="{spark(72, 22, 9)}" fill="{c["spark"]}"/>'
            f'<path d="{n}" fill="{c["ink"]}"/>')


def wordmark(c, x=0.0, baseline=68.0, size=60.0):
    """Returns (svg, width, top, bottom)."""
    if WORDMARK == "script":
        a, wa, ba = text_path(PLAYBALL, "Oura", size * 1.07, x, baseline)
        b, wb, bb = text_path(PLAYBALL, "Noir", size * 1.07, x + wa - 2, baseline)
        width = wa + wb - 2
    elif WORDMARK == "caps":
        a, wa, ba = text_path(PLAYFAIR, "OURA", size * .66, x, baseline, tracking=6)
        b, wb, bb = text_path(PLAYFAIR, "NOIR", size * .66, x + wa + 14, baseline, tracking=6)
        width = wa + wb + 14
    else:  # editorial
        a, wa, ba = text_path(PLAYFAIR_ITALIC, "Oura", size, x, baseline)
        b, wb, bb = text_path(PLAYFAIR, "Noir", size, x + wa + 4, baseline)
        width = wa + wb + 4
    top, bottom = min(ba[1], bb[1]), max(ba[3], bb[3])
    return f'<path d="{a}" fill="{c["oura"]}"/><path d="{b}" fill="{c["ink"]}"/>', width, top, bottom


def lockup_parts(c):
    """Symbol + wordmark side by side; returns (svg, viewBox width, height)."""
    _, _, top, bottom = wordmark(c)
    cap_mid = (top + bottom) / 2
    mark_size = (bottom - top) * 1.8
    gap = mark_size * .22
    word, wwidth, _, _ = wordmark(c, x=mark_size + gap)
    scale = mark_size / 100
    y0 = cap_mid - mark_size / 2
    svg = f'<g transform="translate(0 {y0:.2f}) scale({scale:.4f})">{mark(c)}</g>{word}'
    # viewBox: crop to content
    return svg, mark_size + gap + wwidth + 2, y0, mark_size


def variables(c):
    """Same artwork with colours as CSS variables (falls back to the light colours)."""
    return {k: f"var(--logo-{k}, {v})" for k, v in c.items()}


def write_sprite():
    v = variables(LIGHT)
    lock, w, y0, h = lockup_parts(v)
    word, ww, top, bottom = wordmark(v)
    sprite = (
        '<svg xmlns="http://www.w3.org/2000/svg">'
        '<!-- OuraNoir logo. Generated by tools/make-logo.py - do not edit by hand. -->'
        f'<symbol id="logo-mark" viewBox="0 0 100 100">{mark(v)}</symbol>'
        f'<symbol id="logo-word" viewBox="-1 {top - 2:.1f} {ww + 3:.1f} {bottom - top + 4:.1f}">{word}</symbol>'
        f'<symbol id="logo-lockup" viewBox="0 {y0:.1f} {w:.1f} {h:.1f}">{lock}</symbol>'
        '</svg>\n')
    (ROOT / "img/logo.svg").write_text(sprite)
    return w / h


def standalone(name, inner, vb, bg=None):
    rect = f'<rect x="{vb[0]}" y="{vb[1]}" width="{vb[2]}" height="{vb[3]}" fill="{bg}"/>' if bg else ""
    (ROOT / "img/brand" / name).write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{" ".join(f"{x:.1f}" for x in vb)}">'
        f'<title>OuraNoir</title>{rect}{inner}</svg>\n')


def main():
    (ROOT / "img/brand").mkdir(parents=True, exist_ok=True)
    ratio = write_sprite()
    for theme, c, bg in (("light", LIGHT, None), ("dark", DARK, None)):
        lock, w, y0, h = lockup_parts(c)
        pad = h * .25
        standalone(f"ouranoir-logo-{theme}.svg", lock, (-pad, y0 - pad, w + 2 * pad, h + 2 * pad), bg)
        standalone(f"ouranoir-mark-{theme}.svg", mark(c), (-8, -8, 116, 116), bg)
    # Profile picture / app icon: symbol on a solid tile
    standalone("ouranoir-avatar-midnight.svg", mark(DARK), (-14, -14, 128, 128), MIDNIGHT)
    standalone("ouranoir-avatar-ivory.svg", mark(LIGHT), (-14, -14, 128, 128), "#FFFCF8")
    # Favicon: rounded Midnight tile, slightly heavier ring so it holds up at 16px
    fav_mark = mark(DARK).replace('stroke-width="6.5"', 'stroke-width="8"')
    (ROOT / "img/favicon.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="-6 -6 112 112">'
        f'<rect x="-6" y="-6" width="112" height="112" rx="24" fill="{MIDNIGHT}"/>{fav_mark}</svg>\n')
    print(f"logo written (wordmark: {WORDMARK}, lockup ratio {ratio:.2f}:1)")


if __name__ == "__main__":
    main()
